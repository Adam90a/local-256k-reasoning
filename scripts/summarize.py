#!/usr/bin/env python3
"""Build results/processed/*.md tables from raw run files."""
import glob, json, os, collections
os.chdir(os.path.expanduser("~/local-reasoning-research"))
os.makedirs("results/processed", exist_ok=True)

rows = []
for f in sorted(glob.glob("results/raw/*/*_s*_*[0-9].json")):
    d = json.load(open(f))
    pk = f.replace(".json", ".monitor.csv.peaks.json")
    p = json.load(open(pk)) if os.path.exists(pk) else {}
    s = d["scores"]
    bad = [k for k, v in s.items() if not k.startswith("_") and not v["ok"]]
    rows.append(dict(label=d["label"], suite=d.get("suite", "easy"), seed=d["seed"], tokens=d["prompt_tokens_server"],
                     score=f"{sum(v['ok'] for k, v in s.items() if not k.startswith('_'))}/{sum(1 for k in s if not k.startswith('_'))}",
                     hard=s.get("_score_hard"), prefill_s=round(d["prefill_s"]), prefill_tps=round(d["prefill_tps"] or 0),
                     gen_tps=round(d["gen_tps"] or 0, 1), out_tok=d["output_tokens"], vram=p.get("vram_mib"),
                     rss=p.get("proc_rss_gb"), swapin=p.get("swap_in_total_mb"), temp=p.get("temp_c"),
                     trunc=d["truncated"], missed=",".join(bad) or "-", file=os.path.basename(f)))

hdr = ["label", "suite", "seed", "tokens", "score", "prefill_s", "prefill_tps", "gen_tps", "out_tok", "vram", "rss", "swapin", "temp", "trunc", "missed"]
with open("results/processed/longctx.md", "w") as o:
    o.write("# Long-context runs (generated by scripts/summarize.py)\n\n")
    o.write("vram = peak MiB on PRO 4000; rss = server peak GB (includes mmapped weights); swapin = MB swapped in during run; temp = peak °C.\n\n")
    o.write("| " + " | ".join(hdr) + " |\n|" + "---|" * len(hdr) + "\n")
    for r in sorted(rows, key=lambda r: (r["label"], r["tokens"] or 0, r["seed"])):
        o.write("| " + " | ".join(str(r[h]) for h in hdr) + " |\n")

q = collections.defaultdict(dict)
for f in glob.glob("results/raw/quality/*/*.jsonl"):
    label, task = f.split("/")[-2], os.path.basename(f)[:-6]
    rs = [json.loads(l) for l in open(f)]
    toks = [((r.get("usage") or {}).get("completion_tokens") or 0) for r in rs]
    q[label][task] = dict(ok=sum(r["ok"] for r in rs), n=len(rs), cut=sum(r.get("finish") == "length" for r in rs),
                          mean_tok=round(sum(toks) / max(len(toks), 1)), tps=round(sum(r.get("tps") or 0 for r in rs) / max(len(rs), 1), 1))
with open("results/processed/quality.md", "w") as o:
    o.write("# Short-context quality (AIME 2026 odd-numbered 15; LiveCodeBench v6 newest 10 AtCoder-hard)\n\n")
    o.write("| model | AIME | LCB | AIME length-capped | LCB length-capped | mean output tokens (AIME/LCB) | decode tok/s |\n|---|---|---|---|---|---|---|\n")
    for label, t in sorted(q.items()):
        a, l = t.get("aime", {}), t.get("lcb", {})
        o.write(f"| {label} | {a.get('ok','-')}/{a.get('n','-')} | {l.get('ok','-')}/{l.get('n','-')} | {a.get('cut','-')} | {l.get('cut','-')} | "
                f"{a.get('mean_tok','-')}/{l.get('mean_tok','-')} | {a.get('tps','-')} |\n")
print(open("results/processed/longctx.md").read())
print(open("results/processed/quality.md").read())
